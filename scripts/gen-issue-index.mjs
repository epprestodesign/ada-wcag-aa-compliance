// Generates src/ada/_kit/issue-index.generated.js from the issue story files:
// Storybook ids, item counts, item states, Before verdicts and agent verdicts
// per issue. Run after adding or changing an issue:  pnpm ada:index
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const adaDir = join(root, 'src/ada')

// Storybook's id sanitizer (storybook/internal/csf `sanitize`).
const sanitize = (s) =>
  s
    .toLowerCase()
    .replace(/[ ’–—―′¿'`~!@#$%^&*()_|+\-=?;:'",.<>{}[\]\\/]/gi, '-')
    .replace(/-+/g, '-')
    .replace(/^-+/, '')
    .replace(/-+$/, '')
const toId = (title) => title.split('/').map(sanitize).join('-')

const count = (src, re) => {
  const out = {}
  for (const m of src.matchAll(re)) out[m[1]] = (out[m[1]] ?? 0) + 1
  return out
}
// Slice one exported story's template out of the file.
const section = (src, name) => {
  const start = src.indexOf(`export const ${name} `)
  if (start < 0) return ''
  const next = src.indexOf('export const ', start + 10)
  return src.slice(start, next < 0 ? undefined : next)
}

const index = {}
for (const dir of readdirSync(adaDir)) {
  const full = join(adaDir, dir)
  if (!dir.startsWith('epic-') || !statSync(full).isDirectory()) continue
  for (const file of readdirSync(full).filter((f) => /^ENG-\d+\.stories\.js$/.test(f))) {
    const src = readFileSync(join(full, file), 'utf8')
    const id = file.replace('.stories.js', '')
    const title = src.match(/title:\s*'([^']+)'/)?.[1]
    if (!title) continue
    const issueView = section(src, 'Issue')
    const beforeView = section(src, 'Before')
    const proposalView = section(src, 'Proposal')
    const itemsBlock = src.match(/const ITEMS = \{([\s\S]*?)\n\}/)?.[1] ?? ''
    index[id] = {
      title,
      storyId: toId(title),
      file: relative(root, join(full, file)),
      items: (itemsBlock.match(/\bn:\s*\d+/g) ?? []).length,
      itemStates: count(itemsBlock, /state:\s*'(\w+)'/g),
      before: count(beforeView, /<ada-before[^>]*?\sstatus="([\w-]+)"/g),
      agents: count(issueView, /<agent-check[^>]*?\sverdict="(\w+)"/g),
      agentSlugs: [...new Set([...issueView.matchAll(/<agent-check[^>]*?\sagent="([\w-]+)"/g)].map((m) => m[1]))],
      options: {
        linear: (proposalView.match(/<ada-option(?![^>]*origin="agent")[^>]*>/g) ?? []).length,
        agent: (proposalView.match(/<ada-option[^>]*origin="agent"/g) ?? []).length,
      },
    }
  }
}

const out = `// AUTO-GENERATED by scripts/gen-issue-index.mjs — do not edit by hand.
export const ISSUE_INDEX = ${JSON.stringify(index, null, 2)}
`
writeFileSync(join(adaDir, '_kit/issue-index.generated.js'), out)
console.log(`Indexed ${Object.keys(index).length} issues → src/ada/_kit/issue-index.generated.js`)
